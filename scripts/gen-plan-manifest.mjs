// scripts/gen-plan-manifest.mjs
// Regenerates src/plans/manifest.ts from every week file's `export const meta = {...}`.
// Run manually after adding/removing a week file: `node scripts/gen-plan-manifest.mjs`.
//
// Why this exists: meta (title/date/id) needs to be available eagerly for the sidebar/homepage
// across ALL plans, but the full plan module (recipe DATA + component) should only load when a
// specific plan is opened. If the eager meta read and the lazy full-module import both point at
// the same source file, bundlers just include it eagerly anyway (no real code-splitting). Pulling
// meta into this separate, tiny, hand-independent file breaks that coupling for real.

import { readdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { join, relative } from "node:path";

const PLANS_DIR = join(import.meta.dirname, "..", "src", "plans");
const YEAR_DIRS = ["2025", "2026"];

function findPlanFiles() {
  const files = [];
  for (const year of YEAR_DIRS) {
    const dir = join(PLANS_DIR, year);
    let entries;
    try {
      entries = readdirSync(dir);
    } catch {
      continue;
    }
    for (const name of entries) {
      if (!/\.(jsx|tsx)$/.test(name)) continue;
      files.push(join(dir, name));
    }
  }
  return files;
}

function extractMeta(filePath) {
  const src = readFileSync(filePath, "utf8");
  const m = src.match(/export const meta = (\{[\s\S]*?\n\});/);
  if (!m) return null;
  // meta objects here are plain string-literal object literals — safe to eval in this
  // controlled, repo-local context (not user input).
  // eslint-disable-next-line no-eval
  const meta = eval(`(${m[1]})`);
  return meta;
}

// The week's thematic tagline ("Kürbis, Mais & Pilze 🌽 · Erntefrisch mild · Balanced") lives as
// a plain `subtitle="..."` prop on <PlanTemplate>, not inside meta — pulling it straight out of
// the source text (like extractMeta does) means the register/homepage can show it without ever
// loading the full week module, and without touching all 40+ week files to duplicate it into meta.
function extractFocus(filePath) {
  const src = readFileSync(filePath, "utf8");
  const m = src.match(/subtitle="([^"]*)"/);
  return m ? m[1] : undefined;
}

const files = findPlanFiles();
const rows = [];
for (const filePath of files) {
  const meta = extractMeta(filePath);
  if (!meta?.id || !meta?.startDate) {
    console.warn("skip (no meta):", filePath);
    continue;
  }
  const focus = extractFocus(filePath);
  const path = "./" + relative(PLANS_DIR, filePath).split("\\").join("/");
  rows.push({ ...meta, ...(focus ? { focus } : {}), path: `./plans/${path.slice(2)}` });
}
rows.sort((a, b) => a.startDate.localeCompare(b.startDate));

const out = `// src/plans/manifest.ts
// AUTO-GENERATED by scripts/gen-plan-manifest.mjs — do not hand-edit.
// Regenerate after adding/removing a week file: node scripts/gen-plan-manifest.mjs

export type PlanManifestEntry = {
  id: string;
  title?: string;
  startDate: string;
  lang?: string;
  sidebar?: string;
  focus?: string;
  path: string;
};

export const PLAN_MANIFEST: PlanManifestEntry[] = ${JSON.stringify(rows, null, 2)};
`;

writeFileSync(join(PLANS_DIR, "manifest.ts"), out);
console.log(`Wrote ${rows.length} plan entries to src/plans/manifest.ts`);
