/** Schale: Mitte/Rand (x,y), halbe Breite rx, Randhöhe ry, Tiefe h. children liegen im Inneren. */
function Bowl({ x = 160, y = 90, rx = 70, ry = 15, h = 56, tint = INK, o = 0.1, band = false, children }:
  { x?: number; y?: number; rx?: number; ry?: number; h?: number; tint?: string; o?: number; band?: boolean; children?: ReactNode }) {
  const l = x - rx, r = x + rx, kx = rx * 0.55, ky = ry * 0.55;
  const body = `M${l} ${y}C${l + 4} ${y + h * 0.7} ${x - rx * 0.5} ${y + h} ${x} ${y + h}C${x + rx * 0.5} ${y + h} ${r - 4} ${y + h * 0.7} ${r} ${y}C${r} ${y + ky} ${x + kx} ${y + ry} ${x} ${y + ry}C${x - kx} ${y + ry} ${l} ${y + ky} ${l} ${y}Z`;
  return (
    <>
      <B d={`${l} ${y} ${l} ${y - ky} ${x - kx} ${y - ry} ${x} ${y - ry} ${x + kx} ${y - ry} ${r} ${y - ky} ${r} ${y}`} w={2.4} o={0.7} />
      {children}
      <Shape d={body} c={tint} o={o} />
      <B d={`${l} ${y} ${l} ${y + ky} ${x - kx} ${y + ry} ${x} ${y + ry} ${x + kx} ${y + ry} ${r} ${y + ky} ${r + 1} ${y - 2}`} w={3.2} />
      <B d={`${l - 1} ${y - 1} ${l + 4} ${y + h * 0.72} ${x - rx * 0.5} ${y + h + 1} ${x} ${y + h} ${x + rx * 0.5} ${y + h} ${r - 6} ${y + h * 0.72} ${r - 1} ${y + 5}`} w={7} />
      <B d={`${x - rx * 0.34} ${y + h} ${x - rx * 0.36} ${y + h + 12} ${x + rx * 0.2} ${y + h + 11} ${x + rx * 0.34} ${y + h + 1}`} w={4.5} />
      {band && <B d={`${l + 13} ${y + h * 0.5} ${x - 30} ${y + h * 0.78} ${x + 30} ${y + h * 0.78} ${r - 15} ${y + h * 0.46}`} w={5} c={BLUE} o={0.75} />}
    </>
  );
}

